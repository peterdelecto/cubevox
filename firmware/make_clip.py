#!/usr/bin/env python3
"""Turns a WAV into a C header holding a mono 16-bit 48 kHz clip for the bench build.

Stereo is folded to mono by taking the left channel. The clip loops in place of the SAI
input while the bench op clip is on. build.sh writes the header to <out dir>-gen/bench_clip.h.

  ./make_clip.py ../samples/adam_vox_sample2_4s.wav /tmp/cubevox-fw-bench-gen/bench_clip.h
"""

import argparse
import array
import sys
import wave

SAMPLE_RATE_HZ = 48000
SAMPLE_BYTES = 2
PER_LINE = 16


def read_mono(src):
    """Left-channel samples of a 48 kHz 16-bit WAV."""
    try:
        with wave.open(src) as w:
            ch, sw, sr, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
            raw = w.readframes(n)
    except (OSError, wave.Error, EOFError) as e:
        sys.exit(f"[ERROR] {src}: {e}")
    if sr != SAMPLE_RATE_HZ or sw != SAMPLE_BYTES:
        sys.exit(f"[ERROR] {src}: need 48 kHz 16-bit, got {sr} Hz {sw * 8}-bit")
    samples = array.array("h")
    samples.frombytes(raw)
    if sys.byteorder == "big":
        samples.byteswap()  # WAV data is little-endian
    mono = samples[0::ch]
    if not mono:
        sys.exit(f"[ERROR] {src}: no samples")
    return mono


def write_header(dst, src, x):
    with open(dst, "w") as f:
        f.write(f"// Generated by make_clip.py from {src}: {len(x)} samples, 48 kHz mono int16.\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write(f"constexpr uint32_t kBenchClipLen = {len(x)};\n")
        f.write("const int16_t kBenchClip[kBenchClipLen] = {\n")
        for i in range(0, len(x), PER_LINE):
            f.write("  " + ",".join(str(v) for v in x[i:i + PER_LINE]) + ",\n")
        f.write("};\n")


def main():
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n", 1)[0])
    ap.add_argument("wav")
    ap.add_argument("header")
    a = ap.parse_args()
    x = read_mono(a.wav)
    write_header(a.header, a.wav, x)
    print(f"[clip] {a.wav}: {len(x) / SAMPLE_RATE_HZ:.2f} s mono, {len(x) * SAMPLE_BYTES // 1024} KB of flash")


if __name__ == "__main__":
    main()
